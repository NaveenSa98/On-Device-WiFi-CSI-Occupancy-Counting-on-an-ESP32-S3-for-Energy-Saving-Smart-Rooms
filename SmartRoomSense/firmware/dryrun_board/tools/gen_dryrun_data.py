"""Generate the C files for the board dry run (Step 1.11).

Run ONCE from the SmartRoomSense/ folder (read-only on your models/data):

    .venv\\Scripts\\python.exe firmware\\dryrun_board\\tools\\gen_dryrun_data.py

Reads  (never modified):
    models/Wicount/cnn_taskA_win{W}_int8.tflite
    models/Wicount/cnn_taskA_win{W}_preprocess.json
    models/Wicount/dryrun_samples_win{W}.npz      (X_prepared = float input)
Writes into firmware/dryrun_board/main/:
    model_win{W}.cc          g_model_win{W}[], g_model_win{W}_len
    test_windows_win{W}.cc   g_test_x_win{W}[5][W*52]   int8 inputs
                             g_test_expected_win{W}[5]  int8 outputs from the notebook's
                                                        Python interpreter (main reference)
                             g_test_expected_ref_win{W}[5]  same, Python reference kernels
                             g_test_label_win{W}[5]     true class (0 = 1 person, 1 = 2 people)
                             g_pre_win{W}               numbers from the JSON

Task A of the notebook = 1 vs 2 people:  label 0 = 1 person, label 1 = 2 people.
Class rule used by the notebook: score > 0.5, with score = (int8 - zp) * scale.
For these models (scale 1/256, zp -128) that is the same as  int8 > 0.

"expected" is produced by running the SAME int8 .tflite in Python, with the same
interpreter type and the same float->int8 formula as notebook cell 28
(run_int8), so any board difference comes from the board's kernels.
"""
import json
from pathlib import Path

import numpy as np
import tensorflow as tf

ROOT = Path(__file__).resolve().parents[3]          # .../SmartRoomSense
MODELS = ROOT / "models" / "Wicount"
OUT = ROOT / "firmware" / "dryrun_board" / "main"
WINDOWS = (128, 512)
TEST_IDX = (0, 6, 8, 12, 16)   # of the 20 saved windows: 0, 6, 8 = 1 person; 12, 16 = 2 people
N_SC = 52


def c_array(values, per_line=16):
    """Format a flat list of ints as C initializer lines."""
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join(str(int(v)) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def write_model(w):
    data = (MODELS / f"cnn_taskA_win{w}_int8.tflite").read_bytes()
    text = (
        f"// AUTO-GENERATED by tools/gen_dryrun_data.py - do not edit.\n"
        f"// Source: models/Wicount/cnn_taskA_win{w}_int8.tflite\n"
        f'#include "dryrun_data.h"\n\n'
        f"// alignas(16): TFLite Micro wants the model buffer aligned.\n"
        f"alignas(16) const unsigned char g_model_win{w}[] = {{\n"
        f"{c_array(list(data), 16)}\n}};\n"
        f"const unsigned int g_model_win{w}_len = {len(data)};\n"
    )
    (OUT / f"model_win{w}.cc").write_text(text, newline="\n")


OPT = tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES  # notebook cell 28
REF = tf.lite.experimental.OpResolverType.BUILTIN_REF                       # plain reference kernels


def int8_reference(w, x_float, resolver=OPT):
    """Run the int8 tflite in Python; return (int8 inputs, int8 outputs).

    Python's own two kernel sets differ slightly (win 512 window 8: -76 vs -73),
    so we keep both: OPT = the notebook's numbers, REF = TFLite reference kernels.
    """
    interp = tf.lite.Interpreter(
        model_path=str(MODELS / f"cnn_taskA_win{w}_int8.tflite"),
        experimental_op_resolver_type=resolver,
    )
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    scale, zp = inp["quantization"]
    xq, yq = [], []
    for x in x_float:
        q = np.clip(np.round(x[None] / scale + zp), -128, 127).astype(np.int8)  # notebook formula
        interp.set_tensor(inp["index"], q)
        interp.invoke()
        xq.append(q[0])
        yq.append(int(interp.get_tensor(out["index"]).ravel()[0]))
    return xq, yq


def write_tests(w):
    pre = json.loads((MODELS / f"cnn_taskA_win{w}_preprocess.json").read_text())
    npz = np.load(MODELS / f"dryrun_samples_win{w}.npz")
    x = npz["X_prepared"][list(TEST_IDX)]
    labels = npz["y"][list(TEST_IDX)].astype(int)       # 0 = 1 person, 1 = 2 people
    assert x.shape == (len(TEST_IDX), w, N_SC), x.shape
    xq, yq = int8_reference(w, x)                 # notebook numbers (main "expected")
    _, yq_ref = int8_reference(w, x, REF)         # reference kernels (extra information)
    rows = ",\n".join("{\n" + c_array(q.ravel(), 26) + "\n}" for q in xq)
    text = (
        f"// AUTO-GENERATED by tools/gen_dryrun_data.py - do not edit.\n"
        f"// Source windows (index in dryrun_samples_win{w}.npz): {list(TEST_IDX)}\n"
        f'#include "dryrun_data.h"\n\n'
        f"const PreprocessInfo g_pre_win{w} = {{ {pre['input_scale']!r}f, {pre['input_zero_point']}, "
        f"{pre['output_scale']!r}f, {pre['output_zero_point']} }};\n\n"
        f"const int8_t g_test_expected_win{w}[{len(yq)}] = {{ {', '.join(map(str, yq))} }};\n\n"
        f"// Same model run by Python's plain reference kernels. Differs from the line above\n"
        f"// only where Python's own optimised and reference kernels disagree.\n"
        f"const int8_t g_test_expected_ref_win{w}[{len(yq)}] = {{ {', '.join(map(str, yq_ref))} }};\n\n"
        f"// True label of each window: 0 = 1 person, 1 = 2 people (Task A).\n"
        f"const int8_t g_test_label_win{w}[{len(yq)}] = {{ {', '.join(map(str, labels))} }};\n\n"
        f"const int8_t g_test_x_win{w}[{len(xq)}][{w * N_SC}] = {{\n{rows}\n}};\n"
    )
    (OUT / f"test_windows_win{w}.cc").write_text(text, newline="\n")
    print(f"win{w}: expected int8 outputs = {yq}, ref kernels = {yq_ref}, true labels = {labels.tolist()}")


if __name__ == "__main__":
    for win in WINDOWS:
        write_model(win)
        write_tests(win)
    print("done ->", OUT)
